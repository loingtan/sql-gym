-- Chapter 12, Phantom Files ---------------------------------------------------------------------
-- Screenshots stored as paths, and a snapshot of the file server after a "restore".
DROP TABLE IF EXISTS bugs.phantom_screenshots CASCADE;
CREATE TABLE bugs.phantom_screenshots (
  bug_id          bigint NOT NULL REFERENCES bugs.bugs(bug_id),
  image_id        int    NOT NULL,
  screenshot_path varchar(100),          -- just a string: nothing checks the file exists
  caption         varchar(100),
  PRIMARY KEY (bug_id, image_id)
);

DROP TABLE IF EXISTS bugs.phantom_file_store CASCADE;
CREATE TABLE bugs.phantom_file_store (   -- what is really on /var/bugs/screenshots after the restore
  path    text  PRIMARY KEY,
  content bytea NOT NULL
);

