-- Chapter 11, 31 Flavors ------------------------------------------------------------------------
-- A status ENUM type, and a salutation column restricted by a CHECK constraint.
DROP TABLE IF EXISTS bugs.flavor_bugs CASCADE;
DROP TYPE IF EXISTS bugs.flavor_status CASCADE;
CREATE TYPE bugs.flavor_status AS ENUM ('NEW', 'IN PROGRESS', 'CODE COMPLETE', 'FIXED', 'VERIFIED', 'CLOSED', 'WONTFIX');

CREATE TABLE bugs.flavor_bugs (
  bug_id  bigint PRIMARY KEY,
  summary varchar(80)        NOT NULL,
  status  bugs.flavor_status NOT NULL DEFAULT 'NEW'   -- the allowed values live in metadata
);

