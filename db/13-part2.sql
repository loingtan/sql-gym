-- Chapter 13, Index Shotgun ---------------------------------------------------------------------
-- The book's "index everything" bugs table. The perf exercises create their indexes in Setup.
DROP TABLE IF EXISTS bugs.shotgun_bugs CASCADE;
CREATE TABLE bugs.shotgun_bugs (
  bug_id        bigint PRIMARY KEY,
  date_reported date          NOT NULL,
  summary       varchar(80)   NOT NULL,
  status        varchar(20)   NOT NULL,
  hours         numeric(9,2)
);

INSERT INTO bugs.shotgun_bugs
SELECT bug_id, date_reported, summary, status, hours FROM bugs.bugs;

CREATE INDEX shotgun_bugs_bug_id_idx           ON bugs.shotgun_bugs (bug_id);
CREATE INDEX shotgun_bugs_summary_idx          ON bugs.shotgun_bugs (summary);
CREATE INDEX shotgun_bugs_hours_idx            ON bugs.shotgun_bugs (hours);
CREATE INDEX shotgun_bugs_status_idx           ON bugs.shotgun_bugs (status);
CREATE INDEX shotgun_bugs_status_date_idx      ON bugs.shotgun_bugs (status, date_reported);
CREATE INDEX shotgun_bugs_date_idx             ON bugs.shotgun_bugs (date_reported);
CREATE INDEX shotgun_bugs_date_status_idx      ON bugs.shotgun_bugs (date_reported, status);
CREATE INDEX shotgun_bugs_bug_date_status_idx  ON bugs.shotgun_bugs (bug_id, date_reported, status);
CREATE UNIQUE INDEX shotgun_bugs_summary_bug_key ON bugs.shotgun_bugs (summary, bug_id);

-- Chapter 14, Fear of the Unknown ---------------------------------------------------------------
